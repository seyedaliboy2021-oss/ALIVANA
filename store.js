function deepClone(obj) { return JSON.parse(JSON.stringify(obj)); }

function loadSiteData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return deepClone(DEFAULT_DATA);
    const saved = JSON.parse(raw);
    // shallow-merge top level so new default fields (from future updates) survive
    return Object.assign(deepClone(DEFAULT_DATA), saved);
  } catch (e) {
    console.error('خطا در خواندن اطلاعات ذخیره‌شده، مقادیر پیش‌فرض بارگذاری شد.', e);
    return deepClone(DEFAULT_DATA);
  }
}

function saveSiteData(data) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    return true;
  } catch (e) {
    console.error('ذخیره‌سازی ناموفق بود (احتمالاً حجم فایل رسانه زیاد است).', e);
    return false;
  }
}

function resetSiteData() {
  localStorage.removeItem(STORAGE_KEY);
}
